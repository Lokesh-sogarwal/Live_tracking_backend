import { z } from 'zod';
import { FEEDBACK_CATEGORIES, FEEDBACK_STATUSES, Feedback, FeedbackReply, User } from '../models/index.js';
import { can, roleDisplayName, roleRank } from '../services/roles.js';
import { createNotification } from '../services/notifications.js';
import { createMailer } from '../services/mailer.js';
import { badRequest, conflict, forbidden, notFound } from '../utils/errors.js';

export const reference = (id) => `FB-${String(id).padStart(6, '0')}`;
const iso = (d) => (d ? new Date(d).toISOString() : null);
const idParam = z.coerce.number().int().positive();

export const schemas = {
  idParam: z.object({ id: idParam }),
  replyParam: z.object({ id: idParam, reply_id: z.string().regex(/^[0-9a-f]{24}$/, 'Invalid reply') }),
  listQuery: z.object({
    status: z.enum(FEEDBACK_STATUSES).optional(),
    category: z.enum(FEEDBACK_CATEGORIES).optional(),
    priority: z.enum(['low', 'normal', 'high']).optional(),
    from: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).optional(),
    to: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).optional(),
    q: z.string().trim().max(100).optional(),
  }),
  reply: z.object({
    message: z.string({ required_error: 'Write a reply' }).trim().min(2, 'Write a reply').max(5000),
    // Generated by the client per reply; a retried request returns the first reply.
    idempotency_key: z.string().trim().min(8).max(100),
    resolve: z.boolean().optional(),
  }),
  update: z
    .object({ status: z.enum(FEEDBACK_STATUSES).optional(), priority: z.enum(['low', 'normal', 'high']).optional() })
    .refine((b) => b.status || b.priority, { message: 'Nothing to update' }),
};

// Same rule as the existing inbox (GET /data/get_feedback): operator or above, plus the
// "Feedbacks" feature permission (a superadmin can revoke it per role).
export const canManageFeedback = async (req) => roleRank(req.roleKey) >= roleRank('operator') && (await can(req.roleKey, 'Feedbacks'));

const historyEntry = (actor, action, detail) => ({
  at: new Date(),
  actor: actor === 'system' ? 'system' : actor.userId,
  actorName: actor === 'system' ? 'System' : actor.fullname,
  action,
  ...(detail ? { detail: String(detail).slice(0, 300) } : {}),
});

const summary = (f) => ({
  id: f.feedbackId,
  reference: reference(f.feedbackId),
  subject: f.subject || '',
  message: f.message,
  category: f.category || 'general',
  priority: f.priority || 'normal',
  status: f.status || 'new',
  created_at: iso(f.createdAt),
  last_reply_at: iso(f.lastReplyAt),
  reply_count: f.replyCount || 0,
});

// For the submitter: who replied (name and role) and when — nothing about delivery or staff.
const replyForSubmitter = (r) => ({ id: String(r._id), message: r.message, author_name: r.authorName, author_role: r.authorRole, created_at: iso(r.createdAt) });
const replyForStaff = (r) => ({
  ...replyForSubmitter(r),
  email: { status: r.email.status, skip_reason: r.email.skipReason, sent_at: iso(r.email.sentAt), attempts: r.email.attempts, error: r.email.lastError },
});

export function createFeedbackController(ctx) {
  const { config, logger } = ctx;
  const mailer = ctx.mailer ?? createMailer(config);
  const tz = config.APP_TIMEZONE;

  // Sends one reply email. The atomic claim (pending and unclaimed -> claimed) guarantees a
  // single send per attempt even if this runs twice; "sent" is recorded only after the
  // provider accepted the message.
  async function deliver(replyId, log) {
    const reply = await FeedbackReply.findOneAndUpdate(
      { _id: replyId, 'email.status': 'pending', 'email.claimedAt': null },
      { $set: { 'email.claimedAt': new Date() }, $inc: { 'email.attempts': 1 } },
      { new: true },
    ).lean();
    if (!reply) return;
    const fb = await Feedback.findById(reply.feedback).lean();
    const ref = reference(fb.feedbackId);
    try {
      await mailer.send({
        // Same key on every attempt: if an earlier attempt reached the provider, it won't send twice.
        idempotencyKey: `feedback-reply/${reply._id}`,
        to: reply.email.to,
        subject: `Update on Your Feedback — Reference #${ref}`,
        text:
          `Hello,\n\n${reply.authorName} (${reply.authorRole}) replied to your feedback ${ref}` +
          `${fb.subject ? ` "${fb.subject}"` : ''}:\n\n${reply.message}\n\n` +
          `You sent this feedback on ${new Date(fb.createdAt).toLocaleDateString('en-GB', { timeZone: tz, dateStyle: 'medium' })}.\n` +
          (config.appPublicUrl ? `Read the whole conversation after signing in: ${config.appPublicUrl}/my_feedback/${fb.feedbackId}\n` : ''),
      });
      // Audit entry first: once the reply reads "sent", the history already says so.
      await Feedback.updateOne({ _id: fb._id }, { $push: { history: historyEntry('system', 'Reply emailed', `to the submitter (attempt ${reply.email.attempts})`) } });
      await FeedbackReply.updateOne({ _id: reply._id }, { $set: { 'email.status': 'sent', 'email.sentAt': new Date(), 'email.lastError': null } });
    } catch (err) {
      // Only the error class/message: never the message body or credentials.
      const safe = String(err?.code || err?.message || 'send failed').slice(0, 200);
      log.warn({ err: { code: err?.code, responseCode: err?.responseCode } }, 'Feedback reply email failed');
      await Feedback.updateOne({ _id: fb._id }, { $push: { history: historyEntry('system', 'Reply email failed', `attempt ${reply.email.attempts}: ${safe}`) } });
      await FeedbackReply.updateOne({ _id: reply._id }, { $set: { 'email.status': 'failed', 'email.lastError': safe } });
    }
  }

  const loadStaff = async (req) => {
    if (!(await canManageFeedback(req))) throw forbidden();
    const fb = await Feedback.findOne({ feedbackId: req.params.id }).populate('user', 'fullname email roleKey userId emailVerifiedAt').lean();
    if (!fb) throw notFound('Feedback not found');
    return fb;
  };

  const staffDetail = async (fb) => {
    const replies = await FeedbackReply.find({ feedback: fb._id }).sort({ createdAt: 1 }).lean();
    return {
      ...summary(fb),
      submitter: fb.user
        ? { name: fb.user.fullname, email: fb.email, role: roleDisplayName(fb.user.roleKey), email_verified: Boolean(fb.user.emailVerifiedAt) }
        : { name: 'Deleted user', email: fb.email, role: null, email_verified: false },
      replies: replies.map(replyForStaff),
      history: (fb.history || []).map((h) => ({ at: iso(h.at), actor: h.actorName, action: h.action, detail: h.detail ?? null })),
      email_enabled: mailer.enabled,
    };
  };

  return {
    async mine(req, res) {
      const rows = await Feedback.find({ user: req.user._id }).sort({ createdAt: -1 }).limit(200).lean();
      res.json(rows.map(summary));
    },

    // Only the caller's own feedback: someone else's ID answers 404, not 403.
    async mineDetail(req, res) {
      const fb = await Feedback.findOne({ feedbackId: req.params.id, user: req.user._id }).lean();
      if (!fb) throw notFound('Feedback not found');
      const replies = await FeedbackReply.find({ feedback: fb._id }).sort({ createdAt: 1 }).lean();
      res.json({ ...summary(fb), replies: replies.map(replyForSubmitter) });
    },

    async list(req, res) {
      if (!(await canManageFeedback(req))) throw forbidden();
      const q = req.validatedQuery;
      const filter = {};
      if (q.status) filter.status = q.status === 'new' ? { $in: ['new', null] } : q.status;
      if (q.category) filter.category = q.category === 'general' ? { $in: ['general', null] } : q.category;
      if (q.priority) filter.priority = q.priority === 'normal' ? { $in: ['normal', null] } : q.priority;
      if (q.from || q.to) {
        filter.createdAt = {};
        if (q.from) filter.createdAt.$gte = new Date(`${q.from}T00:00:00Z`);
        if (q.to) filter.createdAt.$lt = new Date(new Date(`${q.to}T00:00:00Z`).getTime() + 86400_000);
      }
      const rows = await Feedback.find(filter).sort({ createdAt: -1 }).limit(1000).populate('user', 'fullname').lean();
      const needle = q.q?.toLowerCase();
      res.json(
        rows
          .map((f) => ({ ...summary(f), submitter_name: f.user?.fullname ?? 'Deleted user', submitter_email: f.email }))
          .filter((f) => !needle || [f.reference, f.subject, f.message, f.submitter_name, f.submitter_email].some((v) => (v || '').toLowerCase().includes(needle))),
      );
    },

    async detail(req, res) {
      res.json(await staffDetail(await loadStaff(req)));
    },

    async reply(req, res) {
      const log = req.log ?? logger;
      const fb = await loadStaff(req);
      const { message, idempotency_key, resolve } = req.body;

      const existing = await FeedbackReply.findOne({ feedback: fb._id, idempotencyKey: idempotency_key }).lean();
      if (existing) return res.json({ ...(await staffDetail(fb)), duplicate: true });

      const submitter = fb.user ? await User.findById(fb.user._id).lean() : null;
      let email;
      if (!mailer.enabled) email = { status: 'skipped', skipReason: 'not_configured' };
      else if (!submitter) email = { status: 'skipped', skipReason: 'no_account' };
      else if (!submitter.emailVerifiedAt && !config.FEEDBACK_EMAIL_UNVERIFIED) email = { status: 'skipped', skipReason: 'unverified_email' };
      else email = { status: 'pending', to: submitter.email };

      let reply;
      try {
        reply = await FeedbackReply.create({
          feedback: fb._id,
          author: req.user._id,
          authorUserId: req.user.userId,
          authorName: req.user.fullname,
          authorRole: roleDisplayName(req.roleKey),
          message,
          idempotencyKey: idempotency_key,
          email,
        });
      } catch (err) {
        if (err.code === 11000) return res.json({ ...(await staffDetail(fb)), duplicate: true });
        throw err;
      }

      const status = resolve ? 'resolved' : 'replied';
      await Feedback.updateOne(
        { _id: fb._id },
        {
          $set: { status, lastReplyAt: reply.createdAt },
          $inc: { replyCount: 1 },
          $push: { history: historyEntry(req.user, resolve ? 'Replied and resolved' : 'Replied', email.status === 'skipped' ? `email not sent (${email.skipReason})` : 'email queued') },
        },
      );
      if (submitter) {
        await createNotification(
          {
            user: submitter,
            message: `Reply to your feedback ${reference(fb.feedbackId)}: ${message.slice(0, 120)}${message.length > 120 ? '…' : ''}`,
            type: 'feedback_reply',
            link: `/my_feedback/${fb.feedbackId}`,
          },
          { tz, logger: log },
        ).catch((err) => log.warn({ err: { message: err.message } }, 'Feedback reply notification failed'));
      }
      // The reply is saved; email goes out after the response so a slow provider never
      // holds the dashboard up. Its outcome is visible in the reply's email status.
      res.status(201).json(await staffDetail(await Feedback.findById(fb._id).populate('user', 'fullname email roleKey userId emailVerifiedAt').lean()));
      if (email.status === 'pending') deliver(reply._id, log).catch((err) => log.error({ err: { message: err.message } }, 'Feedback email worker failed'));
    },

    async retryEmail(req, res) {
      const log = req.log ?? logger;
      const fb = await loadStaff(req);
      if (!mailer.enabled) throw conflict('Email is not configured on this server');
      const reopened = await FeedbackReply.findOneAndUpdate(
        { _id: req.params.reply_id, feedback: fb._id, 'email.status': 'failed' },
        { $set: { 'email.status': 'pending', 'email.claimedAt': null } },
        { new: true },
      );
      if (!reopened) throw conflict('Only a failed email can be retried');
      await Feedback.updateOne({ _id: fb._id }, { $push: { history: historyEntry(req.user, 'Email retry requested') } });
      await deliver(reopened._id, log); // waits, so the caller sees the new outcome
      res.json(await staffDetail(await Feedback.findById(fb._id).populate('user', 'fullname email roleKey userId emailVerifiedAt').lean()));
    },

    async update(req, res) {
      const fb = await loadStaff(req);
      const set = {};
      const notes = [];
      if (req.body.status && req.body.status !== (fb.status || 'new')) {
        set.status = req.body.status;
        notes.push(`status ${fb.status || 'new'} → ${req.body.status}`);
      }
      if (req.body.priority && req.body.priority !== (fb.priority || 'normal')) {
        set.priority = req.body.priority;
        notes.push(`priority ${fb.priority || 'normal'} → ${req.body.priority}`);
      }
      if (!notes.length) throw badRequest('Nothing changed');
      await Feedback.updateOne({ _id: fb._id }, { $set: set, $push: { history: historyEntry(req.user, 'Updated', notes.join(', ')) } });
      res.json(await staffDetail(await Feedback.findById(fb._id).populate('user', 'fullname email roleKey userId emailVerifiedAt').lean()));
    },
  };
}
